        <h1>Política de privacidad</h1>
        <p class="legal-updated">Última actualización: 16 de octubre de 2026</p>

        <p>
            En Amerishop (Tecpán, Chimaltenango, Guatemala) respetamos tu privacidad. Esta política explica
            qué datos recopilamos cuando usas nuestra tienda en línea, para qué los usamos y qué puedes hacer con ellos.
        </p>

        <h2>1. Datos que recopilamos</h2>
        <ul>
            <li><strong>Datos de tu cuenta:</strong> nombre, apellido, correo electrónico, número de teléfono y contraseña (guardada cifrada; nunca la vemos).</li>
            <li><strong>Inicio de sesión con Google:</strong> si eliges esta opción, Google nos comparte tu nombre, tu correo electrónico y un identificador de tu cuenta. No recibimos tu contraseña de Google.</li>
            <li><strong>Direcciones de envío</strong> que guardes para tus pedidos.</li>
            <li><strong>Pedidos y pujas:</strong> los productos que compras, los montos, las fechas y las pujas que haces en las subastas.</li>
            <li><strong>Notificaciones:</strong> si las activas, guardamos los datos técnicos que tu navegador genera para poder enviarte avisos (por ejemplo, cuando cambia el estado de tu pedido o ganas una subasta).</li>
            <li><strong>Registro de actividad:</strong> para la seguridad de la tienda guardamos un registro de las acciones importantes (por ejemplo, inicios de sesión, pedidos y cambios hechos por el personal), con la fecha, la dirección IP y el tipo de navegador.</li>
        </ul>

        <h2>2. Para qué usamos tus datos</h2>
        <ul>
            <li>Crear y proteger tu cuenta, y verificar tu correo electrónico.</li>
            <li>Procesar tus pedidos, coordinar el pago y la entrega contigo (por ejemplo, por WhatsApp o teléfono).</li>
            <li>Gestionar las subastas: registrar tus pujas y avisarte si ganas.</li>
            <li>Enviarte notificaciones sobre tus pedidos y subastas, solo si las activaste.</li>
            <li>Enviarte correos necesarios para el servicio, como códigos de verificación o de recuperación de contraseña.</li>
            <li>Proteger la tienda: detectar accesos indebidos y saber quién hizo cada cambio.</li>
            <li>Elaborar estadísticas internas de ventas (por ejemplo, qué categorías se venden más). Son de uso interno y no se comparten.</li>
        </ul>

        <h2>3. Información visible para otros usuarios</h2>
        <p>
            Cuando pujas en una subasta, tu <strong>nombre</strong> aparece en el historial de pujas de ese producto,
            junto con el monto ofrecido. No mostramos tu apellido, correo, teléfono ni dirección.
        </p>

        <h2>4. Con quién compartimos tus datos</h2>
        <p>No vendemos ni alquilamos tus datos personales. Solo intervienen terceros en estos casos:</p>
        <ul>
            <li><strong>Google</strong>, si inicias sesión con tu cuenta de Google.</li>
            <li><strong>El servicio de notificaciones de tu navegador</strong> (Google, Mozilla, Apple o Microsoft), que entrega los avisos que activaste.</li>
            <li><strong>Google (Gmail)</strong>, que usamos para enviarte los correos de la tienda, como los códigos de verificación y de recuperación de contraseña.</li>
            <li><strong>WhatsApp</strong>, únicamente cuando tú decides escribirnos para confirmar un pedido.</li>
            <li>Autoridades, solo si la ley nos obliga a hacerlo.</li>
        </ul>

        <h2>5. Dónde se guardan tus datos</h2>
        <p>
            La tienda funciona en servidores de un proveedor de servicios en la nube (actualmente Microsoft Azure,
            en Estados Unidos). Por eso tus datos pueden guardarse fuera de Guatemala. La conexión con la tienda
            siempre es cifrada (HTTPS).
        </p>

        <h2>6. Almacenamiento en tu navegador</h2>
        <p>
            Para mantener tu sesión iniciada guardamos un identificador de sesión en el almacenamiento local
            de tu navegador. No usamos cookies de publicidad ni herramientas de rastreo de terceros.
            Si cierras sesión, ese identificador se elimina.
        </p>

        <h2>7. Cuánto tiempo conservamos tus datos</h2>
        <p>
            Conservamos los datos de tu cuenta mientras la tengas activa. El historial de pedidos puede
            conservarse el tiempo necesario para fines contables y de atención de reclamos. El registro de
            actividad y las estadísticas de ventas se conservan de forma permanente y no se modifican, como
            respaldo de seguridad y del historial del negocio.
        </p>

        <h2>8. Tus derechos</h2>
        <p>
            Puedes pedirnos en cualquier momento que te digamos qué datos tenemos sobre ti o que los corrijamos.
            Escríbenos a
            <a href="mailto:comazariegoscruz04@gmail.com">comazariegoscruz04@gmail.com</a> y te responderemos lo antes posible.
            También puedes desactivar las notificaciones desde tu cuenta o desde la configuración de tu navegador.
        </p>

        <h2>9. Seguridad</h2>
        <p>
            Protegemos tu información con medidas como el cifrado de contraseñas y conexiones seguras.
            Aun así, ningún sistema es completamente infalible, por lo que te recomendamos no compartir tu contraseña.
        </p>

        <h2>10. Menores de edad</h2>
        <p>
            La tienda no está dirigida a menores de 13 años y no recopilamos a sabiendas sus datos. Si eres padre,
            madre o tutor y crees que un menor nos dio sus datos, escríbenos y los revisaremos.
        </p>

        <h2>11. Cambios a esta política</h2>
        <p>
            Si cambiamos esta política, actualizaremos la fecha de "Última actualización" en esta página.
        </p>

        <h2>12. Contacto</h2>
